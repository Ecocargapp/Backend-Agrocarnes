// Convierte un código a su auxiliar de 8 dígitos:
//   explícito en AUXILIAR · 6 dígitos → + '01' · 4 dígitos → + '9501' (subcuenta "otros") · 8 dígitos → igual.
export function auxiliar(codigo) {
  const c = String(codigo).trim();
  if (/^\d{8}$/.test(c)) return c;
  if (AUXILIAR[c]) return AUXILIAR[c];
  if (/^\d{6}$/.test(c)) return `${c}01`;
  if (/^\d{4}$/.test(c)) return `${c}9501`;
  throw new Error(`Código contable inválido: ${codigo}`);
}

// Grupo para los informes y naturaleza, a partir del código.
export function clasificar(codigo) {
  const c = String(codigo);
  let naturaleza = ['1', '5', '6'].includes(c[0]) ? 'debito' : 'credito';
  if (c.startsWith('1592')) naturaleza = 'credito';
  if (c.startsWith('240802') || c.startsWith('4175')) naturaleza = 'debito';
  let grupo;
  if (c.startsWith('15') || c.startsWith('16') || c.startsWith('17') || c.startsWith('18')) grupo = 'activo_no_corriente';
  else if (c[0] === '1') grupo = 'activo_corriente';
  else if (c.startsWith('210510')) grupo = 'pasivo';
  else if (c[0] === '2') grupo = 'pasivo';
  else if (c[0] === '3') grupo = 'patrimonio';
  else if (c.startsWith('42')) grupo = 'ingreso_no_operacional';
  else if (c[0] === '4') grupo = 'ingreso';
  else if (c.startsWith('5160')) grupo = 'depreciacion';
  else if (c.startsWith('52')) grupo = 'gasto_ventas';
  else if (c.startsWith('53')) grupo = 'gasto_no_operacional';
  else if (c[0] === '5') grupo = 'gasto_admin';
  else grupo = 'costo';
  return { naturaleza, grupo };
}

// Nombre de un nivel (1, 2, 4, 6 u 8 dígitos).
export function nombreNivel(codigo, nombreTabla) {
  const c = String(codigo);
  if (NOMBRES[c]) return NOMBRES[c];
  if (nombreTabla) return nombreTabla.toUpperCase();
  if (c.length === 6 && c.endsWith('95')) return NOMBRES[c.slice(0, 4)] || 'OTROS';
  if (c.length === 8) return nombreNivel(c.slice(0, 6));
  return c;
}

